def factorizes(
    domain: Sequence[T],
    source: Callable[[T], Hashable],
    target: Callable[[T], Hashable],
) -> bool:
    decoder: dict[Hashable, Hashable] = {}
    for item in domain:
        key = source(item)
        value = target(item)
        if key in decoder and decoder[key] != value:
            return False
        decoder[key] = value
    return True


def kernel(
    domain: Sequence[T],
    statistic: Callable[[T], Hashable],
) -> frozenset[tuple[int, int]]:
    return frozenset(
        (left, right)
        for left in range(len(domain))
        for right in range(len(domain))
        if statistic(domain[left]) == statistic(domain[right])
    )


def join_partition(
    domain: Sequence[T],
    statistics: Sequence[Callable[[T], Hashable]],
) -> tuple[tuple[int, ...], ...]:
    """Partition generated by the join of the statistics' kernels."""

    parent = list(range(len(domain)))

    def find(index: int) -> int:
        while parent[index] != index:
            parent[index] = parent[parent[index]]
            index = parent[index]
        return index

    def union(left: int, right: int) -> None:
        left_root = find(left)
        right_root = find(right)
        if left_root != right_root:
            parent[right_root] = left_root

    for statistic in statistics:
        buckets: dict[Hashable, list[int]] = {}
        for index, item in enumerate(domain):
            buckets.setdefault(statistic(item), []).append(index)
        for bucket in buckets.values():
            for index in bucket[1:]:
                union(bucket[0], index)

    blocks: dict[int, list[int]] = {}
    for index in range(len(domain)):
        blocks.setdefault(find(index), []).append(index)
    return tuple(sorted(tuple(block) for block in blocks.values()))


def partition_from(
    domain: Sequence[T],
    statistic: Callable[[T], Hashable],
) -> tuple[tuple[int, ...], ...]:
    buckets: dict[Hashable, list[int]] = {}
    for index, item in enumerate(domain):
        buckets.setdefault(statistic(item), []).append(index)
    return tuple(sorted(tuple(block) for block in buckets.values()))


def matvec(
    matrix: tuple[tuple[Fraction, Fraction], tuple[Fraction, Fraction]],
    vector: tuple[Fraction, Fraction],
) -> tuple[Fraction, Fraction]:
    return (
        matrix[0][0] * vector[0] + matrix[0][1] * vector[1],
        matrix[1][0] * vector[0] + matrix[1][1] * vector[1],
    )


def matmul(
    left: tuple[tuple[Fraction, Fraction], tuple[Fraction, Fraction]],
    right: tuple[tuple[Fraction, Fraction], tuple[Fraction, Fraction]],
) -> tuple[tuple[Fraction, Fraction], tuple[Fraction, Fraction]]:
    return (
        (
            left[0][0] * right[0][0] + left[0][1] * right[1][0],
            left[0][0] * right[0][1] + left[0][1] * right[1][1],
        ),
        (
            left[1][0] * right[0][0] + left[1][1] * right[1][0],
            left[1][0] * right[0][1] + left[1][1] * right[1][1],
        ),
    )


def norm_squared(vector: tuple[Fraction, Fraction]) -> Fraction:
    return vector[0] ** 2 + vector[1] ** 2


