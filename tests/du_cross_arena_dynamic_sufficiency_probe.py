def build_histories(max_length: int) -> tuple[History, ...]:
    state = "x1"
    word = ""
    histories = [History(0, word, state)]
    for length in range(1, max_length + 1):
        word += EDGE_KIND[state]
        state = NEXT_STATE[state]
        histories.append(History(length, word, state))
    return tuple(histories)


def erasure_support_is_exact(
    domain: Sequence[T],
    record_map: Callable[[T], Hashable],
    target: Callable[[T], Hashable],
    reveal_probability: Fraction,
) -> bool:
    """Support-level exactness of reveal-or-erase access."""

    observations: list[tuple[T, Hashable]] = []
    for item in domain:
        if reveal_probability > 0:
            observations.append((item, ("revealed", record_map(item))))
        if reveal_probability < 1:
            observations.append((item, ("erased",)))
    return factorizes(
        observations,
        lambda observation: observation[1],
        lambda observation: target(observation[0]),
    )


